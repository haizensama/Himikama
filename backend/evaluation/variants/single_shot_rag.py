"""
himikama/backend/evaluation/variants/single_shot_rag.py
═══════════════════════════════════════════════════════════════
Single-shot RAG baseline for hallucination evaluation.

Purpose:
    Compare Full Himikama against a simple RAG baseline.

Architecture:
    intake
      ↓
    retrieve constitutional articles once
    retrieve case summaries once
      ↓
    one Gemini prompt
      ↓
    structured assessment JSON
      ↓
    Python-rendered final answer

This baseline intentionally does NOT use:
    - fixed 10-step chain
    - Step 1/2 hard gates
    - Step 7 two-stage case retrieval
    - Step 9 cross-validation
    - confidence layer

Important:
    This baseline now returns the same final structured fields as
    Full Himikama for fair quantitative evaluation:

        structured_assessment
        final_potentially_violated_articles
        final_weak_or_uncertain_articles
        final_rejected_articles
        overall_assessment
        precedent_alignment
        article_assessments

    Because this is a single-shot baseline, "articles_identified" is
    only a baseline candidate/debug field derived from retrieved
    constitutional article numbers. It is NOT equivalent to Full
    Himikama Step 4.
═══════════════════════════════════════════════════════════════
"""

