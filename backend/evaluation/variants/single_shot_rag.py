MANDATORY_DISCLAIMER = (
    "This assessment has been generated by an AI system and does not "
    "constitute legal advice. It is intended solely to help you understand "
    "your situation before consulting a qualified attorney."
)

ALLOWED_ARTICLE_STATUSES = {
    "supported",
    "weak_or_uncertain",
    "rejected",
}

ALLOWED_OVERALL_ASSESSMENTS = {
    "likely_viable",
    "weak_or_uncertain",
    "not_viable",
    "time_barred",
    "not_state_actor",
}

ALLOWED_PRECEDENT_ALIGNMENTS = {
    "supports",
    "mixed",
    "weak",
    "contradicts",
    "no_cases",
    "not_assessed",
}

ALLOWED_CONFIDENCE_LEVELS = {
    "high",
    "medium",
    "low",
}


